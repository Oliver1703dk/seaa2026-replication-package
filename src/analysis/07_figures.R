# Color palette (colorblind-friendly)
COL_TREAT <- "#2166AC"
COL_CTRL  <- "#B2182B"
COL_SMALL <- "#2166AC"
COL_LARGE <- "#D6604D"

# --- Load panel for distributions ---
panel <- load_panel()
